// Function to generate realistic synthetic historical candles based on a base price and trend
export function generateCandles(basePrice: number, changePercent: number, count: number = 40): Candle[] {
  const candles: Candle[] = [];
  const now = Date.now();
  const interval = 15 * 60 * 1000; // 15 mins
  const volatility = basePrice * 0.008;
  const trend = (changePercent / 100) / count;

  let currentClose = basePrice * (1 - (changePercent / 100));

  for (let i = 0; i < count; i++) {
    const timestamp = now - (count - i) * interval;
    const dateObj = new Date(timestamp);
    const time = `${dateObj.getHours().toString().padStart(2, '0')}:${dateObj.getMinutes().toString().padStart(2, '0')}`;
    
    const change = (Math.random() - 0.48 + trend) * volatility;
    const open = currentClose;
    const close = Math.max(open + change, 0.01);
    const high = Math.max(open, close) + Math.random() * volatility * 0.7;
    const low = Math.min(open, close) - Math.random() * volatility * 0.7;
    const volume = Math.floor(Math.random() * 500000 + 100000);

    candles.push({
      time,
      timestamp,
      open: Number(open.toFixed(2)),
      high: Number(high.toFixed(2)),
      low: Number(low.toFixed(2)),
      close: Number(close.toFixed(2)),
      volume,
    });

    currentClose = close;
  }

  // Ensure last close matches current basePrice
  if (candles.length > 0) {
    candles[candles.length - 1].close = basePrice;
  }

  return candles;
}

